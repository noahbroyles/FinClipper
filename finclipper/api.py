@api.post("/clips")
@login_required_api
def create_clip():
    if not can_clip():
        return bad_request("Your Jellyfin account is not allowed to download media.", 403)
    config = current_app.config
    data = request.get_json(silent=True) or {}

    item_id = str(data.get("item_id") or "")
    source_id = str(data.get("source_id") or "")
    mode = data.get("mode")
    if not ID_RE.match(item_id):
        return bad_request("Invalid item id")
    if mode not in ("fast", "precise"):
        return bad_request("Mode must be fast or precise")
    try:
        start = media.parse_timestamp(data.get("start"))
        end = media.parse_timestamp(data.get("end"))
    except ValueError as exc:
        return bad_request(str(exc))
    try:
        max_height = int(data.get("max_height") or 0)
    except (TypeError, ValueError):
        return bad_request("Invalid resolution")
    if max_height not in media.ALLOWED_HEIGHTS:
        return bad_request("Invalid resolution")
    if mode == "fast":
        # Stream copy cannot resize.
        max_height = 0

    # Always re-read the item from Jellyfin. This checks the user may still
    # access it, and means stream indexes and paths never come from the browser.
    client = jellyfin_client()
    item = client.get_json(f"/Items/{item_id}", params={"userId": user_id()})
    problem = media.clip_problem(item)
    if problem:
        return bad_request(problem)
    source = next((s for s in item["MediaSources"] if s.get("Id") == source_id), None)
    if source is None:
        return bad_request("Unknown media source (version)")
    problem = media.source_problem(source)
    if problem:
        return bad_request(problem)
    video = media.video_streams(source)[0]

    # audio_index: null means the default track, -1 means no audio.
    raw_audio = data.get("audio_index")
    if raw_audio is None:
        audio_index = media.default_audio_index(source)
    elif isinstance(raw_audio, int) and not isinstance(raw_audio, bool):
        audio_index = raw_audio
    else:
        return bad_request("Invalid audio track")
    audio = None
    if audio_index is not None and audio_index != -1:
        audio = next((s for s in media.audio_streams(source) if s.get("Index") == audio_index), None)
        if audio is None:
            return bad_request("Unknown audio track")

    # Validate the range against the real runtime.
    runtime = media.ticks_to_seconds(source.get("RunTimeTicks") or item.get("RunTimeTicks"))
    if runtime:
        if start >= runtime:
            return bad_request("Start is past the end of the video")
        # Players can report a slightly longer duration than Jellyfin does.
        end = min(end, runtime)
    duration = end - start
    if duration < 0.5:
        return bad_request("The clip must be at least half a second long")
    limit = config["MAX_CLIP_SECONDS"]
    if limit and duration > limit + 0.001:
        return bad_request(f"Clips can be at most {media.format_timestamp(limit, millis=False)} long")

    # Prefer reading the file directly; fall back to streaming it from Jellyfin.
    http_headers = None
    local_path = None
    if source.get("Protocol", "File") == "File":
        local_path = media.resolve_local_path(source.get("Path"), config["PATH_MAP"])
    if local_path is not None:
        input_source = local_path
    elif config["ALLOW_STREAM_FALLBACK"]:
        input_source = client.url(
            f"/Videos/{item_id}/stream?static=true&mediaSourceId={quote(source_id, safe='')}"
        )
        http_headers = f"Authorization: {client.auth_header()}\r\n"
    else:
        return bad_request("The media file is not reachable from FinClipper. Check PATH_MAP and the volume mounts.")

    job_id = uuid.uuid4().hex
    plan = media.plan_output(mode, video, audio)
    command = media.build_ffmpeg_command(
        source=input_source,
        start=start,
        duration=duration,
        video=video,
        audio=audio,
        mode=mode,
        max_height=max_height,
        output_path=config["CLIPS_DIR"] / f"{job_id}.part",
        plan=plan,
        preset=config["X264_PRESET"],
        crf=config["X264_CRF"],
        http_headers=http_headers,
    )
    # Same command with the token hidden, for logs.
    redacted = ["Authorization: <redacted>" if arg == http_headers else arg for arg in command]

    description = plan["description"]
    if mode == "precise" and max_height:
        description += f", max {max_height}p"
    title = media.item_title(item)
    job = Job(
        id=job_id,
        user_id=user_id(),
        item_id=item_id,
        title=title,
        start=start,
        end=end,
        mode=mode,
        description=description,
        filename=media.clip_filename(title, start, end, plan["extension"]),
        extension=plan["extension"],
        command=command,
        redacted_command=redacted,
    )
    try:
        jobs().submit(job)
    except JobLimitError as exc:
        return bad_request(str(exc), 429)
    current_app.logger.info(
        "User %s queued clip %s from %s (%s)",
        session.get("user_name"),
        job.id,
        "local file" if local_path else "Jellyfin stream",
        title,
    )
    return jsonify(job.to_dict()), 202


@api.get("/clips")
@login_required_api
def list_clips():
    item_id = request.args.get("item_id")
    result = [
        job.to_dict()
        for job in jobs().list(user_id())
        if not item_id or job.item_id == item_id
    ]
    return jsonify(items=result)


def owned_job(job_id):
    if not JOB_ID_RE.match(job_id):
        return None
    return jobs().get(job_id, user_id())


@api.get("/clips/<job_id>")
@login_required_api
def get_clip(job_id):
    job = owned_job(job_id)
    if job is None:
        return bad_request("Clip not found", 404)
    return jsonify(job.to_dict())


@api.post("/clips/<job_id>/cancel")
@login_required_api
def cancel_clip(job_id):
    if owned_job(job_id) is None:
        return bad_request("Clip not found", 404)
    job = jobs().cancel(job_id, user_id())
    return jsonify(job.to_dict())


@api.delete("/clips/<job_id>")
@login_required_api
def delete_clip(job_id):
    if owned_job(job_id) is None or not jobs().delete(job_id, user_id()):
        return bad_request("Clip not found", 404)
    return Response(status=204)


@api.get("/clips/<job_id>/download")
@login_required_api
def download_clip(job_id):
    job = owned_job(job_id)
    if job is None:
        return bad_request("Clip not found", 404)
    if job.status != DONE:
        return bad_request("This clip is not ready", 409)
    path = jobs().output_path(job)
    if not path.is_file():
        return bad_request("The clip file has expired", 410)
    mimetype = "video/mp4" if job.extension == "mp4" else "video/x-matroska"
    return send_file(path, mimetype=mimetype, as_attachment=True, download_name=job.filename, max_age=0)
