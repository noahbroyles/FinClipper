"""JSON API used by the single page frontend.

All Jellyfin traffic goes through this server, so the browser never needs
to reach Jellyfin directly and page scripts never handle the access token
(it only travels inside the HttpOnly session cookie).
"""

import re
import uuid
from . import media
from .jobs import DONE, Job, JobLimitError
from .jellyfin import JellyfinClient, JellyfinError
from urllib.parse import parse_qsl, quote, urlencode, urlsplit, urlunsplit
from flask import Blueprint, Response, current_app, jsonify, request, send_file, session, stream_with_context
from .auth import can_clip, jellyfin_client, login_required_api, new_device_id, require_json_for_writes, store_login

api = Blueprint("api", __name__, url_prefix="/api")

# Jellyfin item ids: 32 hex characters, or a dashed GUID.
ID_RE = re.compile(r"^(?:[0-9a-fA-F]{32}|[0-9a-fA-F]{8}-(?:[0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12})$")
# FinClipper job ids are uuid4().hex.
JOB_ID_RE = re.compile(r"^[0-9a-f]{32}$")
# Play session ids are generated by the frontend as hex strings.
PLAY_SESSION_RE = re.compile(r"^[0-9a-zA-Z]{8,64}$")
# The only HLS paths the preview proxy forwards (all under /Videos/{id}/).
HLS_PATH_RE = re.compile(r"^(?:master\.m3u8|main\.m3u8|hls1/[A-Za-z0-9_-]+/-?\d+\.(?:ts|mp4))$")
# Query parameters that carry an access token. Removed from proxied playlists.
TOKEN_PARAMS = {"api_key", "apikey"}

# Library types that can contain videos.
BROWSABLE_COLLECTIONS = {"movies", "tvshows", "homevideos", "musicvideos", "boxsets", "folders", None}
# Item types returned by search.
SEARCH_TYPES = "Movie,Series,Episode,Video,MusicVideo"


# ----- request hooks and error handling -------------------------------------


@api.before_request
def csrf_guard():
    return require_json_for_writes()


@api.errorhandler(JellyfinError)
def handle_jellyfin_error(exc):
    if exc.status == 401:
        # The token was revoked or expired; force a fresh login.
        session.clear()
    return jsonify(error=str(exc)), exc.status


def bad_request(message, status=400):
    return jsonify(error=message), status


def jobs():
    return current_app.extensions["finclipper_jobs"]


def user_id():
    return session["user_id"]


# ----- helpers ---------------------------------------------------------------


def list_item(item):
    """Reduce a Jellyfin BaseItemDto to what list views need."""
    image_tags = item.get("ImageTags") or {}
    return {
        "id": item.get("Id"),
        "name": item.get("Name") or "Untitled",
        "type": item.get("Type"),
        "is_folder": bool(item.get("IsFolder")),
        "collection_type": item.get("CollectionType"),
        "year": item.get("ProductionYear"),
        "series_id": item.get("SeriesId"),
        "series_name": item.get("SeriesName"),
        "season": item.get("ParentIndexNumber"),
        "episode": item.get("IndexNumber"),
        "runtime": media.ticks_to_seconds(item.get("RunTimeTicks")),
        "image_tag": image_tags.get("Primary"),
        "aspect": item.get("PrimaryImageAspectRatio"),
    }


def list_response(data):
    return jsonify(
        items=[list_item(item) for item in data.get("Items") or []],
        total=data.get("TotalRecordCount", 0),
    )


def query_int(name, default, low, high):
    """Read an integer query parameter clamped to [low, high]."""
    try:
        value = int(request.args.get(name, default))
    except ValueError:
        value = default
    return max(low, min(high, value))


def strip_token_params(uri):
    """Remove api_key / ApiKey query parameters from a playlist URI."""
    parts = urlsplit(uri)
    if not parts.query:
        return uri
    query = [
        (key, value)
        for key, value in parse_qsl(parts.query, keep_blank_values=True)
        if key.lower() not in TOKEN_PARAMS
    ]
    return urlunsplit(parts._replace(query=urlencode(query)))


def rewrite_playlist(text):
    """Strip tokens from every URI in an m3u8 playlist.

    URIs are either whole non-comment lines, or URI="..." attributes on tags
    such as EXT-X-MAP. All of Jellyfin's URIs are relative, so they resolve
    against the proxy URL in the browser without further changes.
    """
    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            line = strip_token_params(stripped)
        elif 'URI="' in line:
            line = re.sub(r'URI="([^"]*)"', lambda m: f'URI="{strip_token_params(m.group(1))}"', line)
        lines.append(line)
    return "\n".join(lines) + "\n"


# ----- authentication --------------------------------------------------------


@api.get("/server")
def server_info():
    """Public server name for the login page."""
    info = jellyfin_client().public_info()
    return jsonify(name=info.get("ServerName"), version=info.get("Version"))


@api.post("/login")
def login():
    data = request.get_json(silent=True) or {}
    username = str(data.get("username") or "").strip()
    password = str(data.get("password") or "")
    if not username:
        return bad_request("Enter your Jellyfin username")
    device_id = new_device_id()
    config = current_app.config
    client = JellyfinClient(
        config["JELLYFIN_URL"],
        device_id=device_id,
        verify_tls=config["JELLYFIN_VERIFY_TLS"],
    )
    result = client.authenticate(username, password)
    store_login(result, device_id)
    return jsonify(ok=True)


@api.post("/logout")
def logout():
    if session.get("token"):
        jellyfin_client().logout()
    session.clear()
    return jsonify(ok=True)


